ON E.NAME = C.NAME 



-- * WRITE A QUERY TO DISPLAY THE PRODUCT NAME, LIST PRICE, CATEGORY ID, AND CATEGORY NAME USING
--   INNER JOIN BETWEEN THE PRODUCTS AND CATEGORIES TABLES

SELECT p.product_name , p.list_price , p.category_id , c.category_name FROM production.products AS p  
INNER JOIN production.categories  AS c
ON p.category_id = c.category_id
ORDER BY product_name DESC 

-- * WRITE A QUERY TO DISPLAY THE FULL NAME OF EACH CUSTOMER, THEIR ORDER STATUS, AND ORDER DATE 
--   BY USING AN INNER JOIN BETWEEN THE CUSTOMERS AND ORDERS TABLES

SELECT c.first_name + ' ' + c.last_name AS FULL_NAME , o.order_status , o.order_date FROM sales.customers AS c
INNER JOIN sales.orders AS o
ON c.customer_id = o.customer_id

-- * WRITE A QUERY TO DISPLAY THE PRODUCT NAME, LIST PRICE, CATEGORY ID, CATEGORY NAME,
--   AND BRAND NAME BY USING INNER JOINS BETWEEN THE PRODUCTS, CATEGORIES, AND BRANDS TABLES

SELECT p.product_name , p.list_price , p.category_id , c.category_name , b.brand_name
FROM production.products AS p  
INNER JOIN production.categories  AS c
ON p.category_id = c.category_id
INNER JOIN production.brands AS b
ON p.brand_id = b.brand_id




-- * LEFT JOIN (LEFT TABLE KA SARA DATA OR RIGHT TABLE KA ONLY COMMON DATA )

SELECT P.product_name , OI.order_id , O.order_date , OI.item_id FROM sales.order_items AS OI
LEFT JOIN sales.orders AS O
ON OI.order_id = O.order_id
LEFT JOIN production.products AS P
ON OI.product_id = P.product_id 





-- * RIGHT JOIN (RIGHT TABLE KA SARA DATA OR LEFT TABLE KA ONLY COMMON DATA )


SELECT P.product_name , OI.order_id , O.order_date , OI.item_id FROM sales.order_items AS OI
RIGHT JOIN sales.orders AS O
ON OI.order_id = O.order_id
RIGHT JOIN production.products AS P
ON OI.product_id = P.product_id 

 

 -- * FULL OUTER JOIN (ALL DATA FROM BOTH TABLES )

SELECT P.product_name , OI.order_id , O.order_date , OI.item_id FROM sales.order_items AS OI
FULL OUTER JOIN sales.orders AS O
ON OI.order_id = O.order_id
FULL OUTER JOIN production.products AS P
