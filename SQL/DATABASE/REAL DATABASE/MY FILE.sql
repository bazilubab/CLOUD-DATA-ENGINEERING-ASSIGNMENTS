-- DISPLAY THE CITY AND FULL NAMES OF TWO DIFFERENT CUSTOMERS WHO BELONG TO THE SAME CITY USING
-- A SELF JOIN ON THE SALES.CUSTOMERS TABLE, ENSURING THAT EACH CUSTOMER PAIR APPEARS ONLY ONCE.

SELECT C1.city AS CITY , C1.first_name + ' ' + C1.last_name AS C1_FULLNAME  ,
C2.first_name + ' ' + C2.last_name AS C2_FULLNAME 
FROM sales.customers AS C1 
INNER JOIN sales.customers AS C2 
ON C1.customer_id > C2.customer_id 
AND  C1.city = C2.city

















