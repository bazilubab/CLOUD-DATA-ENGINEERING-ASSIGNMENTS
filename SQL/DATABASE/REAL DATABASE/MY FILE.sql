-- GROUPING ON SAME VALUES 

-- * DISPLAY THE CUSTOMER ID AND ORDER YEAR FOR CUSTOMERS 1 AND 2, SHOWING EACH UNIQUE CUSTOMER 
--   AND ORDER YEAR COMBINATION USING GROUP BY.


SELECT customer_id , YEAR(order_date) AS ORDER_YEAR FROM sales.orders
WHERE customer_id IN(1,2)
GROUP BY
customer_id , YEAR(order_date)

-- * DISPLAY THE CUSTOMER ID AND TOTAL NUMBER OF ORDERS PLACED BY CUSTOMERS 1, 2, AND 155 USING GROUP BY

SELECT customer_id , COUNT(order_id) AS ORDERS_COUNT FROM sales.orders
WHERE customer_id IN(1,2,155)
GROUP BY customer_id

-- * DISPLAY THE CUSTOMER ID, ORDER YEAR, AND TOTAL NUMBER OF ORDERS FOR CUSTOMERS 1, 2, 3, 4, AND 5
--   GROUPED BY CUSTOMER ID AND ORDER YEAR, AND SORTED BY CUSTOMER ID IN ASCENDING ORDER


SELECT customer_id , YEAR(order_date) AS ORDER_YEAR, COUNT(order_id) AS ORDER_COUNT  FROM sales.orders
WHERE customer_id IN(1,2,3,4,5) 
GROUP  BY customer_id , YEAR(order_date)  
ORDER BY customer_id

